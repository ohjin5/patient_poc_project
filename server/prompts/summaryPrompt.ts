"동일 유형 타 부서에서는 환자의 질문에 충분히 답변한 경험과 관련된 긍정 VOC가 확인되었습니다. 이를 참고하여 본 부서에서도 환자 설명 및 질의응답 경험을 강화하는 방향을 검토할 수 있습니다."



